"""Abstract Platform: everything ARES needs from the operating system."""
from __future__ import annotations

from abc import ABC, abstractmethod


class PlatformError(Exception):
    """A short, human-readable failure from the operating system layer."""


class Platform(ABC):
    @abstractmethod
    def open_app(self, name: str) -> bool: ...
    @abstractmethod
    def open_url(self, url: str) -> None: ...
    @abstractmethod
    def open_folder(self, path: str) -> None: ...
    @abstractmethod
    def get_volume(self) -> int: ...
    @abstractmethod
    def set_volume(self, level: int) -> None: ...
    @abstractmethod
    def get_mute(self) -> bool: ...
    @abstractmethod
    def set_mute(self, muted: bool) -> None: ...
    @abstractmethod
    def get_brightness(self) -> int: ...
    @abstractmethod
    def set_brightness(self, level: int) -> None: ...
    @abstractmethod
    def get_theme(self) -> str: ...
    @abstractmethod
    def set_theme(self, mode: str) -> None: ...
    @abstractmethod
    def show_desktop(self) -> None: ...
    @abstractmethod
    def close_active_window(self) -> str:
        """Politely close the foreground window; return its title."""
    @abstractmethod
    def screenshot(self, path: str) -> str: ...
    @abstractmethod
    def recycle(self, paths: list[str]) -> None: ...
    @abstractmethod
    def restore_from_recycle(self, original_paths: list[str]) -> int: ...
    @abstractmethod
    def notify(self, title: str, message: str) -> None: ...
    @abstractmethod
    def schedule_reminder(self, minutes: int, message: str) -> None: ...
